$fixed = 0
Get-ChildItem -Path $base -Recurse -Filter *.kt | ForEach-Object {
    $file = $_.FullName
    $txt = [IO.File]::ReadAllText($file, [Text.Encoding]::UTF8)
    $changed = $false
    foreach ($k in $map.Keys) {
        if ($txt.Contains($k)) {
            $txt = $txt.Replace($k, $map[$k])
            $changed = $true
            $fixed++
        }
    }
    if ($changed) {
        [IO.File]::WriteAllText($file, $txt, [Text.Encoding]::UTF8)
        Write-Host "Fixed: $($_.Name)"
    }
}
Write-Host "Total fixes: $fixed"
